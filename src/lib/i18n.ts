const DICTS: Record<LocaleId, typeof en> = { en, es, pt, fr, de, it, nl };

export type Messages = typeof en;

export function translate(locale: LocaleId, key: string, vars?: Record<string, string | number>) {
  const parts = key.split(".");
  let cur: unknown = DICTS[locale];
  for (const part of parts) {
    if (!cur || typeof cur !== "object") {
      cur = undefined;
      break;
    }
    cur = (cur as Record<string, unknown>)[part];
  }
  let out = typeof cur === "string" ? cur : key;
  if (vars) {
    out = out.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
  }
  return out;
}

export function messages(locale: LocaleId) {
  return DICTS[locale];
}
